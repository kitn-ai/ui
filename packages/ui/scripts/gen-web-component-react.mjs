// Emits react/index.tsx — typed React wrappers for every element — from the
// extracted metadata. Each wrapper renders the custom element and bridges props
// (DOM properties) + on<Event> handlers (CustomEvent listeners) via react/runtime.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { cleanEmittedType as clean } from './_ts-helpers.mjs';

// `clean` now has ONE owner, in _ts-helpers.mjs. This file used to carry a
// byte-identical copy, which is why the function-in-union fix had to be made twice.

// IMPORTS values are relative to src/web-components; rebase to frameworks/react/.
const reactImportPath = (srcElementsRel) =>
  srcElementsRel.startsWith('./')
    ? `../../src/web-components/${srcElementsRel.slice(2)}`
    : `../../src/${srcElementsRel.slice(3)}`;

// Event names are lower-kebab, kai-prefixed (e.g. `kai-message-action`). The React/Solid
// handler prop strips the `kai-` prefix and PascalCases on hyphens → `onMessageAction`.
// EXPORTED because @kitn.ai/blocks restates this rule (it cannot import from
// packages/ui without a build-order dependency this repo does not allow), and
// mcp/tests/blocks-artifacts.test.ts holds both sides to assert they agree for
// every event the kit declares. `export` on a const changes nothing this
// generator writes.
export const onName = (ev) => 'on' + ev.replace(/^kai-/, '').split('-').map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join('');

export function writeReact(root, elements, IMPORTS) {
  const used = new Set();
  const scan = (s) => { for (const n of Object.keys(IMPORTS)) if (new RegExp(`\\b${n}\\b`).test(s)) used.add(n); };
  for (const el of elements) {
    for (const p of el.props) scan(p.type);
    for (const e of el.events) if (e.detail) scan(e.detail);
  }
  const bySource = {};
  for (const n of used) (bySource[reactImportPath(IMPORTS[n])] ??= []).push(n);
  const importLines = Object.entries(bySource)
    .map(([src, names]) => `import type { ${names.sort().join(', ')} } from '${src}';`)
    .join('\n');

  // Every wrapper's ref is typed as ITS element interface, which this same
  // generator chain already emits into src/web-components/web-component-types.d.ts and
  // dist/web-components.d.ts. Imported by the BARE subpath, not `../../src/...`:
  // config/vite/react.ts's srcSpecifiersToDist rewrites relative src/
  // specifiers in the EMITTED declarations by probing for a `.ts`/`.tsx`
  // source, which a `.d.ts` misses, leaving a specifier pointing outside
  // dist/ that verify:dts fails on. A bare self-reference to a subpath the
  // exports map declares is what that guard accepts, and it is what a
  // consumer writes.
  const webComponentTypeImport = `import type {\n${elements
    .map((el) => `  ${el.className},`)
    .sort()
    .join('\n')}\n} from '@kitn.ai/ui/web-components';`;

  const blocks = elements.map((el) => {
    // `universal` props (theme, injected by define.tsx for every web component) are
    // already declared on WebComponentProps, which every wrapper extends — so they
    // are skipped here but still listed in propNames below, which is what tells the
    // runtime to assign them as DOM properties.
    const propLines = el.props.filter((p) => !p.universal).flatMap((p) => [
      ...(p.description ? [`  /** ${p.description} */`] : []),
      `  ${p.name}${p.optional ? '?' : ''}: ${clean(p.type, p.optional)};`,
    ]);
    const eventLines = el.events.flatMap((e) => [
      ...(e.description ? [`  /** ${e.description} */`] : []),
      `  ${onName(e.name)}?: (event: CustomEvent${e.detail ? `<${clean(e.detail, false)}>` : ''}) => void;`,
    ]);
    const propNames = JSON.stringify(el.props.map((p) => p.name));
    const eventMap = `{ ${el.events.map((e) => `${onName(e.name)}: '${e.name}'`).join(', ')} }`;

    const name = el.displayName;
    const propsName = `${name}Props`;
    const webComponentType = el.className;
    // Lazy-import the web component by its SOURCE-MODULE basename (set in gen-web-component-api.mjs),
    // not its tag: the per-web-component build emits dist/web-components/<source-file>.js, so deriving
    // from the tag (e.g. kai-confirm → "confirm") points at a file that does not exist.
    const moduleName = el.module ?? el.tag.replace(/^kai-/, '');
    return `export interface ${propsName} extends WebComponentProps {
${[...propLines, ...eventLines].join('\n')}
}

export const ${name} = /*#__PURE__*/ createWebComponent<${propsName}, ${webComponentType}>(
  '${el.tag}',
  ${propNames},
  ${eventMap},
  () => import('@kitn.ai/ui/web-components/${moduleName}'),
);`;
  }).join('\n\n');

  const out = `'use client';
// AUTO-GENERATED by scripts/gen-web-component-api.mjs — do not edit by hand.
// Typed React wrappers for every kitn custom element. Usage:
//   import { Message } from '@kitn.ai/ui/react';
//   <Message message={msg} onMessageAction={(e) => …} />
// Each wrapper lazy-registers ITS element on first client mount (a dynamic import
// of '@kitn.ai/ui/web-components/<name>'), so a consumer ships only the elements they use
// — not the register-all bundle. SSR-safe: registration fires only in a client effect.
// For eager all-registration call registerAll() or import '@kitn.ai/ui/web-components'.
import { createWebComponent, registerAll, type WebComponentProps } from './runtime';
${webComponentTypeImport}
export { registerAll };
export { useKaiChat } from './use-kai-chat';
export type { UseKaiChatOptions, KaiChatController } from './use-kai-chat';
// The content-model types, re-exported so a consumer can annotate a \`parts\`
// array or an \`addSource\` argument without reaching into the main entry.
export type {
  ChatMessage, ChatMessageAction, CustomAction, AvatarData, FeedbackVote, MessagePart,
  MessageSource, RawOrigin, ToolPart, ToolKind, CardEnvelope, AttachmentData,
} from './use-kai-chat';
export { useVoiceInput } from './use-voice-input';
${importLines}

${blocks}
`;
  writeFileSync(resolve(root, 'frameworks/react/index.tsx'), out);
  console.log(`✓ frameworks/react/index.tsx — ${elements.length} wrappers`);
}
