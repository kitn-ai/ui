/** Anything bigger than this, outside dist/, needs an explicit entry below. */
const MAX_FILE_BYTES = 64 * 1024;

/**
 * Packed files over MAX_FILE_BYTES that are meant to ship, and why. Paths are
 * relative to the package root, exactly as `npm pack` reports them.
 *
 * Before adding an entry, check the file is genuinely REACHABLE by a consumer:
 * an `exports` subpath, an import from shipped code, or documented source that
 * someone reads. "It is generated by the build" is not a reason to ship it.
 */
const ALLOWED_LARGE_FILES = new Map([
  ['src/web-components/web-component-meta.json', 'exported as the `./web-component-meta.json` subpath'],
  ['llms-full.txt', 'shipped LLM context, listed explicitly in `files`'],
]);

/**
 * Rule 3 roots. Every packed path must start with one of these prefixes...
 */
const ALLOWED_ROOT_PREFIXES = ['dist/', 'bin/'];

/**
 * ...or be exactly one of these paths. Mostly top-level (package.json,
 * README.md, ...); `src/web-components/web-component-meta.json` and
 * `src/web-components/icon-names.json` are the two exceptions — nested paths, not
 * top-level, kept here because they're the only `src/` files any `exports`
 * subpath resolves into (see the 2026-08-27 `files` trim history below).
 */
const ALLOWED_EXACT_FILES = new Set([
  'package.json',
  'README.md',
  'LICENSE',
  'NOTICE',
  'theme.css',
  // The light-DOM Solid stylesheet (exported as ./solid.css) and the shared
  // base/component rules it @imports. kit-base.css is not an exports subpath;
  // it ships because solid.css resolves it by relative path.
  'solid.css',
  'kit-base.css',
  'llms.txt',
  'llms-full.txt',
  'src/web-components/web-component-meta.json',
  'src/web-components/icon-names.json',
]);

/**
 * Pure so the self-test below can drive it with synthetic file lists instead
 * of a real `npm pack`. Returns the packed paths that match neither an
 * allowed prefix nor an exact allowlist entry.
 */
function findRootViolations(paths, prefixes = ALLOWED_ROOT_PREFIXES, exact = ALLOWED_EXACT_FILES) {
  return paths.filter((p) => !prefixes.some((prefix) => p.startsWith(prefix)) && !exact.has(p));
}

if (SELF_TEST) {
  const cases = [
    {
      name: 'a clean pack (dist/bin + the two src JSON exports + top-level docs) passes',
      paths: [
        'dist/index.js',
        'dist/custom-elements.json',
        'bin/mcp.js',
        'bin/route.js',
        'src/web-components/web-component-meta.json',
        'src/web-components/icon-names.json',
        'package.json',
        'README.md',
        'NOTICE',
        'theme.css',
        'solid.css',
        'kit-base.css',
        'llms.txt',
        'llms-full.txt',
      ],
      expectViolations: [],
    },
    {
      name: 'a src/ file outside the two JSON exports is caught (the 2026-08-27 regression class)',
      paths: ['dist/index.js', 'src/components/chat/chat-thread.tsx'],
      expectViolations: ['src/components/chat/chat-thread.tsx'],
    },
    {
      name: 'a stray test file outside bin/dist is caught',
      paths: ['dist/index.js', 'bin/mcp.js', 'scripts/some-dev-script.mjs'],
      expectViolations: ['scripts/some-dev-script.mjs'],
    },
  ];

  let failedCases = 0;
  for (const c of cases) {
    const got = findRootViolations(c.paths);
    const ok = JSON.stringify(got.sort()) === JSON.stringify([...c.expectViolations].sort());
    if (!ok) {
      failedCases++;
      console.error(
        `✗ verify-pack-weight self-test: "${c.name}"\n  expected violations: ${JSON.stringify(c.expectViolations)}\n  got: ${JSON.stringify(got)}`,
      );
    }
  }

  if (failedCases > 0) {
    console.error(`\n✗ verify-pack-weight self-test: ${failedCases}/${cases.length} case(s) failed.\n`);
    process.exit(1);
  }
  console.log(`✓ verify-pack-weight self-test: ${cases.length} case(s) behave as specified.`);
  process.exit(0);
}

