// Guards the published tarball against dead weight.
//
// WHY: `files` in package.json ships the whole of `src/` on purpose — consumers
// read source and source maps point into it. That blanket include is also how
// 300 KB of generated JSON (`src/components/component-meta.json`) rode along to
// every consumer for months: nothing imported it, the `exports` map could not
// even reach it, and no existing check looked at what actually gets packed.
//
// WHAT IT CHECKS:
//
//   1. PRECISE — every packed file OUTSIDE `dist/` larger than MAX_FILE_BYTES
//      must be named in ALLOWED_LARGE_FILES, with a reason. Hand-authored and
//      generated-into-source paths are stable, so an exact allowlist works here
//      and names the offender when it trips. Adding a new large artifact under
//      `src/` is then a deliberate, reviewable act instead of an accident.
//
//      `dist/` is deliberately exempt from this rule: its chunk names carry
//      content hashes that change on every build, so an exact allowlist over
//      them would go red on every rebuild and get bumped reflexively — a check
//      that proves nothing. Rule 2 covers dist.
//
//   2. CRUDE — the PACKED tarball must stay under MAX_PACKED_BYTES. Cruder than
//      rule 1 and it names nothing, but it is the backstop for growth rule 1
//      cannot see: bundle bloat inside `dist/`, or a second copy of something
//      already shipped. It asserts PACKED bytes -- a consumer downloads the
//      tarball, so that is the only number here that is a cost rather than a
//      reading off a developer machine's disk. Unpacked size and the file count
//      are PRINTED on every run and never asserted: unpacked file-sum moves
//      OPPOSITE to transfer cost, because per-module output writes many small
//      files and many small files compress better. The 2026-09-18 entry on
//      MAX_PACKED_BYTES below is the measurement that settled it.
//
//      Both figures stay in the success line on purpose. A ceiling is a claim
//      about a cost; the other two are facts a future reader needs to interpret
//      it, and printing them costs nothing.
//
//   3. ROOTS — every packed file must live under an allowed root
//      (ALLOWED_ROOT_PREFIXES) or be one of a short list of exact paths
//      (ALLOWED_EXACT_FILES — mostly top-level, but two are the nested
//      `src/web-components/*.json` files the `./web-component-meta.json` and
//      `./icon-names.json` exports resolve into). This is what pins `files`
//      in package.json
//      shut: the whole point of the 2026-08-27 trim was that `files: ["dist",
//      "src", "bin", ...]` shipped ~3.83 MiB of `src/` no `exports` subpath
//      could reach (only `web-component-meta.json` and `icon-names.json` are
//      reachable). Rules 1 and 2 would not have caught that regression coming
//      back — rule 1 only fires on files over MAX_FILE_BYTES, and a `src/`
//      re-creep of many small files could stay under MAX_UNPACKED_BYTES for a
//      while. Rule 3 fires the moment ANY file outside the allowed roots is
//      packed, named or not, large or not.
//
// Run it AFTER a build. Without `dist/` the tarball is a fraction of its real
// size and every rule would pass vacuously, so a missing `dist/` is a failure,
// not a skip.
//
// Usage:
//   node scripts/verify-pack-weight.mjs               # the real check
//   node scripts/verify-pack-weight.mjs --self-test    # proves rule 3 can fail

