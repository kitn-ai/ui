#!/usr/bin/env node
/**
 * GUARD: every dependency specifier in a workspace manifest matches the specifier
 * `pnpm-lock.yaml` recorded for it.
 *
 * WHY THIS EXISTS, and it has now cost TWO releases. release-please's `node-workspace` plugin
 * rewrites the internal ranges in the release PR -- pre-1.0 a caret cannot cross a minor, so
 * `@kitn.ai/mcp`'s kit range and `@kitn.ai/cli`'s create-kai range both had to move -- and it does
 * NOT regenerate `pnpm-lock.yaml`. The lockfile's importer entries keep the old specifiers, so
 *
 *     ERR_PNPM_OUTDATED_LOCKFILE  Cannot install with "frozen-lockfile" because pnpm-lock.yaml is
 *     not up to date with <ROOT>/packages/mcp/package.json
 *       specifiers in the lockfile don't match specifiers in package.json:
 *       - @kitn.ai/ui (lockfile: ^0.33.0, manifest: ^0.34.0)
 *
 * kills EVERY leg of the merge commit about 30s in, which makes the required checks terminally red
 * on the SHA being published, which makes the publish gate (correctly) refuse. The release then
 * needs a lockfile-only commit plus a fresh dispatch, and the reason is buried in an install log.
 *
 * IT RUNS BEFORE `pnpm install`, WHICH IS LOAD-BEARING. Every other lint in this repo runs after
 * the install step, so on the exact failure this guard exists for, the install fails first and the
 * guard never runs. It is therefore wired as an early step in the same job, alongside the other
 * no-install guards, and it needs nothing but Node and the checkout: it READS the lockfile, it does
 * not run pnpm, so it cannot itself be broken by the staleness.
 *
 * THE FIX IT PRINTS IS THE ONE COMMAND THAT WORKS: `pnpm install --lockfile-only`.
 *
 * It is a line reader rather than a YAML parser, on purpose and with the usual floor: the repo
 * carries no YAML parser in this layer, the shape is generated by pnpm and stable, and a structure
 * this cannot place is a HARD FAILURE rather than a skip -- see the vacuity floors.
 *
 *   node scripts/lint-lockfile-specifiers.mjs
 *   node scripts/lint-lockfile-specifiers.mjs --self-test   # prove it still detects
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');

/**
 * Fields whose specifier the lockfile records per importer.
 *
 * `peerDependencies` is checked for PRESENCE but not for equality, and that is measured rather than
 * assumed: for an auto-installed peer pnpm records the RESOLVED range, so `packages/ui`'s
 * `react: ">=18"` peer sits in the lockfile as `^19.2.7`. Comparing the strings would report a
 * mismatch on every peer in the workspace.
 */
export const LOCKFIELDS = ['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies'];
export const PRESENCE_ONLY_FIELDS = new Set(['peerDependencies']);

/**
 * Floors: today's lockfile has 20+ importers and hundreds of specifiers. A parse that suddenly sees
 * a handful has stopped understanding the file, and would pass vacuously.
 */
export const MIN_IMPORTERS = 8;
export const MIN_SPECIFIERS = 100;

/**
 * The `importers:` section of a pnpm lockfile, as `{ '<relative dir>': { '<dep name>': '<specifier>' } }`.
 *
 * The importer section is the only place with this shape: it opens with a top-level `importers:` key
 * and ends at the next top-level key (`packages:`, `snapshots:`), after which 2-space keys mean
 * something else entirely.
 */
export function parseLockfileImporters(text) {
  const lines = text.split('\n');
  const start = lines.findIndex((line) => line === 'importers:');
  if (start === -1) return { importers: {}, structural: 'the lockfile has no `importers:` section' };
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^[A-Za-z]/.test(lines[i])) {
      end = i;
      break;
    }
  }
  const importers = {};
  let current = null;
  let dep = null;
  for (let i = start + 1; i < end; i += 1) {
    const line = lines[i];
    const importer = /^ {2}([^\s#][^:]*):$/.exec(line);
    if (importer) {
      current = importer[1];
      importers[current] = {};
      dep = null;
      continue;
    }
    const name = /^ {6}'?([^':]+)'?:$/.exec(line);
    if (name && current !== null) {
      dep = name[1];
      importers[current][dep] = undefined;
      continue;
    }
    const specifier = /^ {8}specifier: (.+)$/.exec(line);
    if (specifier && current !== null && dep !== null) {
      importers[current][dep] = specifier[1].trim();
      continue;
    }
    // A different indent, or a key we do not understand, ends the current dependency.
    if (/^ {8}\S/.test(line)) dep = null;
  }
  return { importers, structural: null };
}

/**
 * The importer's own manifest, or null when the directory is not a package any more.
 *
 * THE LOCKFILE'S OWN IMPORTER LIST IS THE AUTHORITY on which directories matter, not a glob walk of
 * ours: the first cut of this file scanned `packages/` and `apps/` only and reported the root
 * (`.`) and every `examples/**` member as a STALE importer, which was the scanner being wrong, not
 * the lockfile. The one question worth asking per importer is whether a manifest is still there.
 */
export function manifestAt(dir, repoRoot = REPO) {
  const file = join(dir === '.' ? repoRoot : join(repoRoot, dir), 'package.json');
  if (!existsSync(file)) return null;
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** The root manifest's `pnpm.overrides`, which rewrites recorded specifiers workspace-wide. */
export function rootOverrides(repoRoot = REPO) {
  try {
    const root = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
    return root.pnpm?.overrides ?? {};
  } catch {
    return {};
  }
}

/** Every member the caller passes, read from disk. Kept for the self-test's convenience. */
export function workspaceManifests(repoRoot = REPO) {
  const out = [];
  for (const parent of ['packages', 'apps']) {
    const dir = join(repoRoot, parent);
    if (!existsSync(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const manifest = join(dir, entry.name, 'package.json');
      if (!existsSync(manifest)) continue;
      out.push({ dir: `${parent}/${entry.name}`, pkg: JSON.parse(readFileSync(manifest, 'utf8')) });
    }
  }
  return out;
}

/**
 * Every mismatch between the manifests and the lockfile. Pure over its arguments, so `--self-test`
 * drives it over fixtures.
 */
export function specifierProblems(importers, members, overrides = {}, rootDir = REPO) {
  const problems = [];

  // A root `pnpm.overrides` entry REPLACES the specifier pnpm records: `packages/ui` declares
  // `vitest: ^4.1.0` while the lockfile says `specifier: 4.1.2`, because the root pins vitest to
  // 4.1.2 for the whole workspace (MEASURED, and the first cut of this file reported every
  // overridden dependency as a mismatch). So the expected value is the override where there is one,
  // and the override itself is what gets checked.
  const overridden = new Set(Object.keys(overrides));
  let overridesApplied = 0;
  const dirOf = (dir) => (dir === '.' ? rootDir : join(rootDir, dir));
  const byDir = new Map(members.map((m) => [m.dir, m]));

  for (const [dir, recorded] of Object.entries(importers)) {
    if (!byDir.has(dir)) {
      problems.push(
        `pnpm-lock.yaml has an importer for ${dir}, which is not a workspace package any more. A stale importer ` +
          `keeps the whole file out of date; run \`pnpm install --lockfile-only\`.`,
      );
      continue;
    }
    const { pkg } = byDir.get(dir);
    for (const field of LOCKFIELDS) {
      for (const [name, spec] of Object.entries(pkg[field] ?? {})) {
        // A selector-form override key (`react@>=18`) is a shape this does not model; it is
        // counted and reported rather than skipped silently.
        const expectedRaw = overridden.has(name) ? overrides[name] : spec;
        const expected = PRESENCE_ONLY_FIELDS.has(field) ? undefined : expectedRaw;
        if (expectedRaw !== spec) overridesApplied += 1;
        const locked = recorded[name];
        if (locked === undefined) {
          problems.push(
            `pnpm-lock.yaml records no ${name} for ${dir} (${field} in package.json). The lockfile is behind the ` +
              `manifest: run \`pnpm install --lockfile-only\`.`,
          );
          continue;
        }
        if (expected !== undefined && locked !== expected) {
          problems.push(
            `${dir}/package.json declares ${field}["${name}"] = ${spec}, but pnpm-lock.yaml recorded ${locked}. ` +
              `\`pnpm install --frozen-lockfile\` refuses this, so EVERY leg of the merge commit fails at install ` +
              `and the publish gate refuses. Run \`pnpm install --lockfile-only\` and commit the result.`,
          );
        }
      }
    }
  }

  // The other direction: a workspace package with no importer at all (a package added without an
  // install). Cheap, and it is the same class.
  for (const { dir, pkg } of members) {
    if (importers[dir] !== undefined) continue;
    if (Object.keys(pkg.dependencies ?? {}).length === 0 && Object.keys(pkg.devDependencies ?? {}).length === 0) continue;
    problems.push(
      `pnpm-lock.yaml has no importer for ${dir}, which declares dependencies. Run \`pnpm install ` +
        `--lockfile-only\` and commit the result.`,
    );
  }
  return problems;
}

function floors(importers, text) {
  const names = Object.keys(importers);
  const specifiers = names.reduce((n, dir) => n + Object.keys(importers[dir]).length, 0);
  const problems = [];
  if (names.length < MIN_IMPORTERS) {
    problems.push(
      `parsed ${names.length} importer(s) out of the lockfile (the floor is ${MIN_IMPORTERS}). A parse this small ` +
        `has stopped understanding the file, and every check below it would pass vacuously.`,
    );
  }
  if (specifiers < MIN_SPECIFIERS) {
    problems.push(
      `parsed ${specifiers} specifier(s) (the floor is ${MIN_SPECIFIERS}). Same reason: a parse that sees almost ` +
        `nothing cannot compare anything.`,
    );
  }
  if (typeof text === 'string' && text.includes('importers:') && !text.includes('specifier:')) {
    problems.push('the lockfile has an `importers:` section but no `specifier:` line anywhere, which no pnpm lockfile does.');
  }
  return problems;
}

if (process.argv.includes('--self-test')) {
  const lock = [
    'lockfileVersion: 9.0',
    '',
    'importers:',
    '',
    '  packages/a:',
    '    dependencies:',
    "      '@kitn.ai/ui':",
    '        specifier: ^0.34.0',
    '        version: link:../ui',
    '      zod:',
    '        specifier: ^4.4.3',
    '        version: 4.4.3',
    '',
    '  packages/b:',
    '    dependencies:',
    '      create-kai:',
    '        specifier: ^0.7.0',
    '        version: link:../create-kai',
    '',
    'packages:',
    "  zod@4.4.3:",
    '    resolution: {integrity: sha512-x}',
    '',
  ].join('\n');
  const member = (dir, dependencies) => ({ dir, pkg: { name: dir, dependencies } });
  const A = member('packages/a', { '@kitn.ai/ui': '^0.34.0', zod: '^4.4.3' });
  const B = member('packages/b', { 'create-kai': '^0.7.0' });
  const { importers } = parseLockfileImporters(lock);

  const probes = [
    ['the parse finds both importers and their specifiers', importers['packages/a']?.['@kitn.ai/ui'] === '^0.34.0' && importers['packages/b']?.['create-kai'] === '^0.7.0'],
    ['it stops at the next top-level key, so `packages:` is not read as an importer', importers['packages'] === undefined],
    ['matching specifiers pass', specifierProblems(importers, [A, B]).length === 0],
    [
      'a bumped manifest range is reported, with the command that fixes it (the live defect)',
      (() => {
        const found = specifierProblems(importers, [A, member('packages/b', { 'create-kai': '^0.8.0' })]);
        return found.some((p) => p.includes('create-kai') && p.includes('^0.7.0') && p.includes('pnpm install --lockfile-only'));
      })(),
    ],
    [
      'a dependency the lockfile has never seen is reported',
      specifierProblems(importers, [A, member('packages/b', { 'create-kai': '^0.7.0', newdep: '^1.0.0' })]).some((p) =>
        p.includes('records no newdep'),
      ),
    ],
    [
      'a STALE importer is reported (the packages/kai case)',
      specifierProblems({ ...importers, 'packages/kai': { zod: '^4.4.3' } }, [A, B]).some((p) =>
        p.includes('not a workspace package any more'),
      ),
    ],
    [
      'a package with dependencies and no importer is reported',
      specifierProblems(importers, [A, B, member('packages/c', { zod: '^4.4.3' })]).some((p) =>
        p.includes('no importer for packages/c'),
      ),
    ],
    [
      'a workspace: specifier compared against a literal is reported',
      specifierProblems(importers, [A, member('packages/b', { 'create-kai': 'workspace:*' })]).some((p) =>
        p.includes('recorded ^0.7.0'),
      ),
    ],
    [
      'VACUITY: a parse too small to have understood the file',
      floors({ 'packages/a': { zod: '^4.4.3' } }, lock).some((p) => p.includes('importer(s)')),
    ],
    ['a lockfile with no importers section is a structural failure', parseLockfileImporters('lockfileVersion: 9.0\n').structural !== null],
  ];
  let failed = 0;
  for (const [what, ok] of probes) {
    console.log(`${ok ? '✓' : '✗'} ${what}`);
    if (!ok) failed += 1;
  }
  if (failed) {
    console.error(`\n✗ lint-lockfile-specifiers self-test: ${failed}/${probes.length} probe(s) misbehaved.\n`);
    process.exit(1);
  }
  console.log(`✓ lint-lockfile-specifiers self-test: ${probes.length} probes behave as specified.`);
  process.exit(0);
}

const lockText = readFileSync(join(REPO, 'pnpm-lock.yaml'), 'utf8');
const { importers, structural } = parseLockfileImporters(lockText);
const overrides = rootOverrides();
export let overrideCount = 0;
const members = Object.keys(importers)
  .map((dir) => ({ dir, pkg: manifestAt(dir) }))
  .filter((m) => m.pkg !== null);
const problems = [
  ...(structural === null ? [] : [structural]),
  ...floors(importers, lockText),
  ...(structural === null ? specifierProblems(importers, members, overrides) : []),
];
if (problems.length) {
  console.error(`✗ lint-lockfile-specifiers: ${problems.length} problem(s):`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}
const specifierCount = Object.values(importers).reduce((n, deps) => n + Object.keys(deps).length, 0);
const overrideNames = Object.keys(overrides);
console.log(
  `✓ lint-lockfile-specifiers: ${Object.keys(importers).length} importer(s), ${specifierCount} specifier(s); every ` +
    `manifest specifier matches the lockfile (${overrideNames.length} root override(s) checked against the override ` +
    `value: ${overrideNames.join(', ')}; peer specifiers checked for presence only, because pnpm records the ` +
    `RESOLVED range for an auto-installed peer).`,
);
